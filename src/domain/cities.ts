export const CITY_NAMES_SORTED = CITIES.map((c) => c.name).sort((a, b) => a.localeCompare(b, 'tr'));

/** Plaka numarasına karşılık gelen il adı (1–81), yoksa null. */
export function cityByPlate(plate: number): string | null {
  return CITIES[plate - 1]?.name ?? null;
}

/** Eski sürümde "ADANA" gibi büyük harfle kaydedilmiş adı listedeki karşılığına çevirir. */
export function normalizeCityName(name: string | undefined): string | undefined {
  if (!name) return name;
  const key = name.toLocaleUpperCase('tr');
  return CITIES.find((c) => c.name.toLocaleUpperCase('tr') === key)?.name ?? name;
}
